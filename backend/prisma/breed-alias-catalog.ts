export function mergeBreedAliases(
  breedName: string,
  aliases: string[] = [],
): string[] {
  const canonicalName = breedName.trim();
  const dedupedAliases: string[] = [];
  const seen = new Set<string>();

  [...aliases, ...(BREED_ALIAS_CATALOG[breedName] || [])].forEach((alias) => {
    const normalizedAlias = alias.trim();
    if (!normalizedAlias || normalizedAlias === canonicalName) {
      return;
    }

    const dedupeKey = normalizedAlias.toLocaleLowerCase();
    if (seen.has(dedupeKey)) {
      return;
    }

    seen.add(dedupeKey);
    dedupedAliases.push(normalizedAlias);
  });

  return dedupedAliases;
}
