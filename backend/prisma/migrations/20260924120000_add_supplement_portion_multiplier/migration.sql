-- 补剂「加量」：份数上限 + 总天数上限
--
-- 背景：补剂订单的固定成本（分装服务费）是按单收的，跟买多少无关。
-- 一个 30 天量的订单和一个 90 天量的订单，服务费都是 9.9 元、分装工时也差不多
-- （分装 8 袋和 2 袋的实际耗时差异很小）。
-- 所以让用户一次多买几份，能把固定成本摊薄——用户每天成本下降，我们单笔利润上升。
--
-- 两条约束（缺一不可，谁也替代不了谁）：
--   1) max_portion_multiplier：份数上限。管"选项别太多"和"单日产能可控"。
--      只靠天数上限的话，一个 7 天的制作单会算出 12 份（90÷7），
--      8 种补剂就是 96 袋，排产不可预期。
--   2) max_total_days：总天数上限。管**效期安全红线**。
--      只靠份数上限的话，一个 40 天的制作单选 3 份 = 120 天，
--      已经贴到粉剂分装效期（6 个月 = 180 天）的 2/3，不安全。
--
-- 默认 3 份 / 90 天：90 天正好是最短分装效期的一半，留足余量。
--
-- 注意：加量的语义是「每个补剂多做几袋**同样规格**的小袋」，
-- 不是「同一袋装更多」——袋子规格是按一个周期的用量选的，装 3 倍会撑爆。

ALTER TABLE "supplement_shop_config"
    ADD COLUMN "max_portion_multiplier" INTEGER NOT NULL DEFAULT 3,
    ADD COLUMN "max_total_days" INTEGER NOT NULL DEFAULT 90;
