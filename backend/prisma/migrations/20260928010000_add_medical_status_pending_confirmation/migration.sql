-- MedicalStatus 增加「待确认」
--
-- 背景（2026-09-28，落实老板拍板的决策 5）：
--   顾客在食谱定制页自述的疾病，会被系统直接写成 CHRONIC（慢性病）。
--   而决策 5 明确写着「系统**不再臆断**"慢性病"；标为待确认 / 仅留来源，
--   由客服或顾客在档案里确认」。
--
--   生产里已经真实发生过一次：一条"肠胃敏感"被写成了 CHRONIC。
--   "肠胃敏感"是不是慢性病，只有兽医能判断，系统不该替他们下结论。
--
-- 因此新增 PENDING_CONFIRMATION：来源是顾客自述、尚未经确认的疾病一律用它，
-- 由顾客/客服在「健康管理」页把状态改成实际情况。
--
-- 已存在的 CHRONIC 记录**不改动**：那是历史数据，
-- 是否要回访确认属于业务决策，不在本迁移里替老板决定。

-- AlterEnum
ALTER TYPE "MedicalStatus" ADD VALUE IF NOT EXISTS 'PENDING_CONFIRMATION';
