-- 犬种表增加「体况分下限」。
--
-- 背景：深胸细腰型犬（灵缇、惠比特等）在理想体态下就能摸到肋骨、
-- 且肋骨上几乎没有脂肪，会被体况问卷如实答成 2-3 分。
-- 算法用体况分反推目标体重（FEDIAF 表 VII-2）：
--   2 分 → 当前体重 x 1.5385（要求增重 54%）
--   3 分 → 当前体重 x 1.3333（要求增重 33%）
-- 结果是一只体态正常的灵缇会被安排增重。
--
-- 修正方式：给这类犬种设一个分数下限。算法里 4 分和 5 分的换算系数
-- 都是 1.0（理想区间、不换算），所以下限 4 =「不会判定它偏瘦到需要增重」。
--
-- 名单与数值都放在这张表里，增删犬种或调整下限只需改数据，
-- 不需要发小程序版本、不需要走微信审核。

ALTER TABLE "dog_breed" ADD COLUMN "bcs_score_floor" INTEGER;

COMMENT ON COLUMN "dog_breed"."bcs_score_floor" IS
  '体况分下限：深胸细腰型犬（灵缇等）填 4，其余留空表示不做修正';

-- 依 WSAVA 官方 BCS 表与生产库犬种目录逐条列举。
--
-- ⚠️ 不能用「猎犬」这类关键词模糊匹配：犬种库里名字含「猎犬」的有 17 个，
--    其中寻血猎犬、巴塞特猎犬、英国/威尔士激飞猎犬、爱尔兰/美国水猎犬、
--    魏玛猎犬、芬兰/瑞典拉普猎犬等都不是深胸细腰型，误判会把真正偏瘦的狗
--    抬到 4 分、漏掉增重计划。
--
-- ⚠️ 「蒙古猎犬」暂不纳入：中文名可能指蒙古细犬（深胸细腰型），也可能指
--    蒙古牧羊护卫犬，无法确认；且生产库该犬种 0 只 —— 放进去没有收益、
--    只有误判风险。确认后可随时 UPDATE 补上，不用发版。
UPDATE "dog_breed" SET "bcs_score_floor" = 4
WHERE "name" IN (
  '灵缇',        -- Greyhound（犬种库里「格力犬」「Greyhound」是它的别名）
  '惠比特犬',    -- Whippet
  '萨路基猎犬',  -- Saluki
  '阿富汗猎犬',  -- Afghan Hound
  '波索尔',      -- Borzoi
  '依比赞猎犬',  -- Ibizan Hound
  '法老王猎犬',  -- Pharaoh Hound
  '细犬'         -- 中国本土细犬（山东细犬 / 陕西细犬），深胸细腰型
);
