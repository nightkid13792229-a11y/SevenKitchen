-- 把「体况分下限」升级为「按犬种定制的选项换算表」。
--
-- ── 为什么改 ──────────────────────────────────────────────
--
-- 上一版给深胸细腰型犬设的是「分数下限 4」（bcs_score_floor），实现为
-- max(算出的分, 4)。实机走查发现它有两个毛病：
--
--   1. 最瘦的两档被压成同一个分数 —— 「一碰就硌手」(2) 和
--      「手放上去就摸到」(3) 都被抬到 4，丢了一档分辨率；
--   2. 灵缇最常见的答案「手放上去就摸到」会被标成「轻微偏瘦」——
--      一只体态正常的灵缇被告知偏瘦，标签是错的。
--
-- ── 改成什么 ──────────────────────────────────────────────
--
-- 每个犬种可以自带一张换算表，按选项顺序给出 5 个分数；
-- 留空则用标准分 2/3/5/7/9。深胸细腰型犬用 4/5/6/7/9：
--
--   选项                     标准犬种   深胸细腰型    理由
--   一碰就硌手，几乎没有肉        2        4      它们的"偏瘦"是常态，不能判成需要增重
--   手放上去就摸到，不用按        3        5      它们的理想体态就是这个手感（4 和 5 都换算系数 1.0，
--                                                但 5 的标签「理想体态」才是对的）
--   要轻轻按一下才摸到           5        6      天生精瘦的犬种需要轻按，说明已经有一层脂肪
--   要用力按才摸到              7        7      一致
--   怎么都摸不到                9        9      一致，保留 9 分（肥胖的灵缇同样存在）
--
-- 关键：这只影响「选项换算成几分」，狗身上存的体况分仍然是
-- dog.bcs_score 同一个字段 —— 能量计算、目标体重、定制食谱读的都是它，
-- 所有犬种走同一条路，不存在"灵缇单独存一份"的情况。
--
-- 名单与换算表都在数据库里，增删犬种或调整分数不用发小程序版本。
--
-- ⚠️ 用「空数组」而不是 NULL 表示"没有特殊换算表"。
--    Prisma 的标量列表（Int[]）在客户端类型上是不可空的 number[]，
--    数据库里放 NULL 会在写入/读取时报类型错误。空数组是 Prisma 下的正确建模，
--    语义也清楚：没有条目 = 用标准分。

ALTER TABLE "dog_breed"
  ADD COLUMN "bcs_score_map" INTEGER[] NOT NULL DEFAULT ARRAY[]::INTEGER[];

COMMENT ON COLUMN "dog_breed"."bcs_score_map" IS
  '体况问卷的选项换算表（按选项顺序 5 个分数）；空数组表示用标准分 2/3/5/7/9。深胸细腰型犬用 {4,5,6,7,9}';

-- 沿用上一版已经挑好的那批犬种（当时设了下限 4 的）：
-- 灵缇（含别名格力犬/Greyhound）、惠比特犬、萨路基猎犬、阿富汗猎犬、
-- 波索尔、依比赞猎犬、法老王猎犬、细犬。
--
-- ⚠️ 仍然不能用「猎犬」这类关键词模糊匹配：犬种库里含「猎犬」的有 17 个，
--    其中寻血猎犬、巴塞特猎犬、激飞猎犬、魏玛猎犬等都不是深胸细腰型，
--    误判会让真正偏瘦的狗拿不到增重计划。
-- ⚠️ 「蒙古猎犬」仍不纳入：中文名可能指蒙古细犬、也可能指蒙古牧羊护卫犬，
--    无法确认；生产库该犬种 0 只，放进去只有误判风险。确认后 UPDATE 一行即可。
UPDATE "dog_breed"
SET "bcs_score_map" = ARRAY[4, 5, 6, 7, 9]
WHERE "name" IN (
  '灵缇',
  '惠比特犬',
  '萨路基猎犬',
  '阿富汗猎犬',
  '波索尔',
  '依比赞猎犬',
  '法老王猎犬',
  '细犬'
);

-- 保底：万一有别的犬种被手工设过下限而没在上面的名单里，也一并转过来
UPDATE "dog_breed"
SET "bcs_score_map" = ARRAY[4, 5, 6, 7, 9]
WHERE "bcs_score_floor" IS NOT NULL
  AND "bcs_score_map" = ARRAY[]::INTEGER[];

ALTER TABLE "dog_breed" DROP COLUMN "bcs_score_floor";
