-- 健康标签的人工修正（2026-10-01，第八期）。
--
-- ── 为什么需要 ──────────────────────────────────────────────
--
--   系统只用关键词从病历自由文本里"猜"狗的疾病领域标签
--   （/肾|肌酐|蛋白尿/ → ckd、renal…），一共 16 类。
--   猜错了、漏猜了，**没有任何入口能改** —— 营养师只能看着 AI 引用错的条目。
--   老板第 24 条：营养师或管理员要能够修改健康标签用来纠错。
--
-- ── 为什么存"改了什么"而不是"最终结果" ──────────────────────
--
--   形状 { "added": [...], "removed": [...] }：
--     · 派生标签 − removed + added = 最终标签
--   这样顾客后来又补了新病历，派生部分仍会自动跟着变，
--   人工修正只覆盖他明确改过的那几个，不会把整份标签冻结在某一时刻。
--
--   ⚠️ 与 recipe_health_tag（食谱合规词表）是两件事：
--      那张表是给食谱打标、筛选、做封面角标用的，与狗无关。

ALTER TABLE "dog"
  ADD COLUMN "health_tag_overrides" JSONB NOT NULL DEFAULT '{}';

COMMENT ON COLUMN "dog"."health_tag_overrides" IS
  '健康标签的人工修正：{ added: string[], removed: string[] }；派生标签 − removed + added = 最终标签';
