-- 疫苗记录留原件（2026-10-01，健康管理第九期）。
--
-- ── 为什么需要 ──────────────────────────────────────────────
--
--   拍疫苗本识别之后，顾客拿回来的只有 AI 抄下来的文字：
--   疫苗名、接种日期、下次到期日。**原件照片没有地方存**。
--
--   疫苗本是接种凭证，出行（检疫）、寄养、换医院都可能要看原件；
--   AI 抄错一个字（把"英特威"抄成别的、把日期抄错一天），
--   没有原件就无从对证，顾客只能重新翻纸质本子。
--
-- ── 为什么与病历/体检/过敏用同一种存法 ──────────────────────
--
--   那三张表都已经是 attachments TEXT[]（COS 上的图片 URL 数组），
--   这里照抄同一套：顾客端"上传原图"、营养师端"看原件"的逻辑可以完全复用，
--   不引入第二种附件表示法。
--
--   默认空数组且 NOT NULL：老记录（手工填的疫苗记录）本来就没有原件，
--   语义上不该是 NULL；也与 checkup_record / medical_record / allergy_record
--   三张表的 attachments 列保持同一种形状（Prisma 生成的 SQL 会省略 NOT NULL，
--   这里显式写上，避免以后这列里混进 NULL 行、将来想收紧又收不紧）。
--
-- ⚠️ 只加列、不加索引：附件只在打开单条记录时按主键读，
--    不会按附件内容检索。

ALTER TABLE "vaccine_record"
  ADD COLUMN "attachments" TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[];

COMMENT ON COLUMN "vaccine_record"."attachments" IS
  '疫苗记录的报告原件（COS 图片 URL 数组）；拍疫苗本识别时写入，手工填写的为空数组';
