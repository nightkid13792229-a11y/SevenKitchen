-- 体检查验数据与检查结论分开（2026-10-02）。
--
-- ── 为什么 ──────────────────────────────────────────────────
--
--   顾客拍一张化验单，AI 会把几十项数值照抄下来。原来只能塞进 findings，
--   于是「检查结论」这个字段里躺着的是：
--     白细胞 -；尿比重 1.025；尿胆原 -；蛋白质 15(0.15)+-；…
--   三个后果：
--     · 家长在记录卡上看到的标题就是这串数字（一堵数字墙）
--     · 营养师端的标签派生拿它当"结论"在扫关键词，噪声很大
--     · 医生真正写的那句结论（如果有）被淹没
--
--   拆成两列之后：findings = 结论段，lab_values = 逐项一行的化验数据。
--   两列都照旧参与标签派生与 AI 分析（只是各归各位）。
--
-- ⚠️ 只加列、不加索引：这两列只在读取单条记录时按主键取，不按内容检索。
--    老数据的 findings 原样保留、不迁移 —— 把数字墙拆回去会猜错，
--    宁可让老记录维持原样。

ALTER TABLE "checkup_record"
  ADD COLUMN "lab_values" TEXT;

COMMENT ON COLUMN "checkup_record"."lab_values" IS
  '化验数据原文（逐项一行：项目 数值 单位）；医生结论在 findings 列';
