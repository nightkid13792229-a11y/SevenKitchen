-- 就诊记录也留化验数据（2026-10-02，老板定稿）。
--
-- ── 为什么 ──────────────────────────────────────────────────
--
--   一次就诊经常包含化验单/检查报告。之前的做法是"按资料类型拆记录"：
--   家长记一次就诊，结果库里多出一条体检记录 —— 与家长的心智不符。
--   老板定的口径：**就诊过程中传的化验单/报告，数字就落在这条就诊记录里**；
--   常规体检的数字落在体检记录里。分类由用户在录入入口选，不由资料类型决定。
--
--   与 checkup_record.lab_values 同名同义：逐项一行的化验数据。
--   医生的诊断/结论仍进 diagnosis（"医生怎么说"），两者不混。
--
-- ⚠️ 只加列、不加索引；老数据不迁移。

ALTER TABLE "medical_record"
  ADD COLUMN "lab_values" TEXT;

COMMENT ON COLUMN "medical_record"."lab_values" IS
  '这次就诊做的化验数据（逐项一行：项目 数值 单位）；诊断结论在 diagnosis 列';
