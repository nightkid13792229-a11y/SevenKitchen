-- 就诊记录拆出「这次做的检查」与「体征」两栏（2026-10-02，老板定稿）。
--
-- ── 为什么 ──────────────────────────────────────────────────
--
--   老板实测一条真实就诊（宝之堂 2026-02-11，胆汁淤积）发现：
--   「处理与提醒」里显示"无"，后面却跟着一长串"全腹部彩超、血常规、斯玛特16项
--   生化、CRP C反应蛋白检查；回家后注意：…" —— 三样东西挤在一个字段里：
--     ① 治疗意见（无）② 处置处方（检查项目清单）③ 医嘱（回家后注意）
--   同一批内容还同时出现在「其它想说的」里，两个字段互相重叠。
--
--   根因不是模型乱放，而是**这个字段没有定义**（提示词只有一句"treatment 写处理方式"）。
--   定稿的字段口径：
--     treatment = 医嘱（医生交代回家要做的）+ 院内处理（少数情况）
--     exams     = 这次做了哪些检查（彩超 / DR / 血常规 …），一行
--     vitals    = 体温、体重、BCS 等体征，照抄报告
--     lab_values= 化验数值（原有）
--     notes     = 补充说明（报告上有、前面栏目装不下的原文要点）
--
--   ⚠️ treatment 列名保持不变（语义收窄成"医嘱"）：
--      改列名要牵动食谱设计器等其它模块，收益不值当。
--      线上 treatment 全为空，语义变化对老数据无影响。
--
-- ⚠️ 只加列、不加索引；老数据不迁移（都是空值）。

ALTER TABLE "medical_record"
  ADD COLUMN "exams" TEXT,
  ADD COLUMN "vitals" TEXT;

COMMENT ON COLUMN "medical_record"."exams" IS
  '这次就诊做了哪些检查（从处置处方/检查单照抄，一行）';
COMMENT ON COLUMN "medical_record"."vitals" IS
  '体征：体温、体重、BCS 等，照抄报告';
COMMENT ON COLUMN "medical_record"."treatment" IS
  '医嘱（2026-10-02 起语义收窄；表单标签「医嘱」）';
