-- ============================================================================
-- 疫苗记录：存下这条记录被归成了哪几类
-- 2026-10-05
--
-- ── 为什么要这一列 ──────────────────────────────────────────────────────
--
-- 老板拍了两个决定：
--   ① "AI 可以扫出名字，并且判断归类" —— 归类由 AI 判，但判的依据是我们
--      维护的那张产品映射表（AI 只能在核心疫苗/狂犬疫苗/钩端螺旋体/其他里选）。
--   ② 手动录入时"允许用户自行填写疫苗产品名称，但是类型还是必填项"。
--
-- 两条都是"人（或 AI）明确指定过归类"，所以归类必须**跟着记录存下来**，
-- 不能再靠读的时候拿名字去猜。
--
-- ── 不存会怎样（修的就是这个）────────────────────────────────────────────
--
-- 在此之前归类是每次读的时候由 vaccineName 现推的，推不出来就**默认当核心苗**。
-- 后果：一针驱虫药「拜宠清」、一支非核心的「犬窝咳」，只要日期落在某个窗口里，
-- 就会把核心苗的那一针标记成**已完成** —— 我们从此不再提醒顾客打疫苗，
-- 而且界面上没人看得出来为什么。这是最坏的一类 bug。
--
-- ── 取值 ────────────────────────────────────────────────────────────────
--   core    核心疫苗（犬瘟热 / 细小 / 腺病毒 / 副流感）
--   rabies  狂犬疫苗
--   lepto   钩端螺旋体（按年）
--   other   其他非核心苗（犬窝咳、冠状病毒、莱姆病…）—— 如实记，但不参与计划
--
-- 一支组合苗可以同时属于好几类（卫佳捌 = core + lepto），所以是数组。
--
-- ── 兼容 ────────────────────────────────────────────────────────────────
-- 老记录（这一列是空数组）在读的时候仍按名字推一次，行为与之前一致 ——
-- 这是**历史数据的兼容路径**，不是主路径。新记录一律由界面/AI 显式带上。
-- 可加性变更：不删列、不改现有列、不影响既有数据。
-- ============================================================================

ALTER TABLE "vaccine_record"
  ADD COLUMN IF NOT EXISTS "kinds" TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[];

COMMENT ON COLUMN "vaccine_record"."kinds" IS
  '这条记录被归成的疫苗类别（core/rabies/lepto/other，可多值）；空数组 = 老记录，读时按名字兼容推导';
