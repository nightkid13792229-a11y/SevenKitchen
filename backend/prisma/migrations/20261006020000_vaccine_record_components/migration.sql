-- ============================================================================
-- 疫苗记录：存下这一针**含哪些病种**
-- 2026-10-06
--
-- ── 为什么要这一列 ──────────────────────────────────────────────────────
--
-- 老板定了新模型：
--   "我们需要把产品库做的更详细一点，也就是每一个产品它里面包含哪些种类的疫苗，
--    然后我们再根据它是否包含犬瘟、细小和腺病毒这三类疫苗，来决定它是不是核心疫苗。
--    ……而在用户需要确认和手动修改的分类中，我们不应该把分类呈现给用户看，
--    我们需要把它拆开，拆成每一个疫苗种类让顾客选择，
--    至于分类的判定则交由后台来完成。"
--
-- 于是：
--   · components（病种）—— 顾客看得见、也勾得动；记录上显示的就是它
--   · kinds（类别）      —— 由病种推导，只给计划用，不再给顾客看、也不手写
--
-- 产品库那边同步改造：37 支苗逐支登记成分，kinds 改由 kindsOfComponents() 推导
-- （有等价性测试钉着：推导值与改造前手写的值逐一相同）。
--
-- ── 取值（闭集）────────────────────────────────────────────────────────
--   cdv        犬瘟热
--   cpv        犬细小病毒
--   cav        犬腺病毒（传染性肝炎 + 呼吸道病）
--   cpi        犬副流感
--   rabies     狂犬病
--   lepto      钩端螺旋体
--   ccov       犬冠状病毒
--   bordetella 博德特氏菌（犬窝咳）
--   lyme       莱姆病
--
-- ── 兼容 ────────────────────────────────────────────────────────────────
-- 老记录这一列为空数组：读的时候仍按名字查产品库/字面规则推一次，
-- 行为与之前一致 —— 这是历史数据的兼容路径，不是主路径。
-- 可加性变更：不删列、不改现有列、不影响既有数据。
-- ============================================================================

ALTER TABLE "vaccine_record"
  ADD COLUMN IF NOT EXISTS "components" TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[];

COMMENT ON COLUMN "vaccine_record"."components" IS
  '这一针含哪些病种（cdv/cpv/cav/cpi/rabies/lepto/ccov/bordetella/lyme，可多值）；空数组 = 老记录，读时按名字兼容推导';
