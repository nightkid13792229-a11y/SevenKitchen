/**
 * 读源码做断言时用的**剥注释**工具。
 *
 * ⚠️⚠️ 为什么必须有它 —— 这个坑 2026-10-14 一天之内踩了三次：
 *
 *   用 `source.includes('hasMore')` 这种判据去检查"某个东西已经删掉了"，
 *   却被**注释里提到这个词**骗了 ✗。而那几条注释恰恰是在解释
 *   "我们为什么把它删掉 / 为什么不该这么写" —— 于是**越解释越误报** ✗。
 *
 *   三次分别是：
 *     ① 小程序：注释里写"曾经写过 width: 100%"，`includes('width:')` 误报
 *     ② 小程序：注释里提到 vaccine-fields，导致 import 漏加没被发现
 *     ③ 后端：注释里写"那个 hasMore 已经删掉了"，`includes('hasMore')` 误报
 *
 * ⇒ 规矩：凡是"源码里**不许出现**某个写法"的断言，
 *   一律先 `stripComments()` 再判 ✓；"**必须出现**"的断言可以不用
 *   （注释里出现不影响"必须"的语义，但为了统一，建议也带上）。
 */
export function stripComments(source: string): string {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, '') // 块注释
    .replace(/(^|[^:])\/\/.*$/gm, '$1'); // 行注释（避开 http:// 这类）
}
