/**
 * 读源码做断言时用的**剥注释**工具。
 *
 * ⚠️⚠️ 为什么要有它 —— 这个坑 2026-10-14 一天之内踩了**四次**：
 *
 *   用 `source.includes('某写法')` 判断"界面上有没有出现这个说法"，
 *   却被**注释里提到那个词**骗了 ✗。而那几条注释恰恰是在解释
 *   "为什么不该这么写 / 曾经踩过什么坑" —— 于是**越解释越误报** ✗。
 *
 *   四次分别是：
 *     ① 注释里写"曾经写过 width: 100%" → `includes('width:')` 误报
 *     ② 注释里提到某个已搬走的工具文件 → 掩盖了漏加的 import
 *     ③ 后端注释写"那个 hasMore 已经删掉了" → `includes('hasMore')` 误报
 *     ④ 注释里引用老板截图"…为必须接种的核心疫苗" →
 *        触发"措辞是建议不是命令"那条断言
 *
 * ⇒ 规矩：凡是"源码里**不许出现**某个说法"的断言，
 *   一律先 `stripComments()` 再判 ✓。
 *   注释是给维护者看的，不是顾客看到的界面文案 ✗。
 */
export function stripComments(source: string): string {
  return (
    source
      /*
       * ⚠️ **模板注释（`<!-- -->`）也要剥** —— `.vue` 文件里的注释大半在模板里，
       *    只剥 JS 注释等于没剥（2026-10-14 实测：漏了这条，断言仍被注释触发 ✗）。
       */
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/\/\*[\s\S]*?\*\//g, '') // JS 块注释
      .replace(/(^|[^:])\/\/.*$/gm, '$1') // JS 行注释（避开 http:// 这类）
  )
}
